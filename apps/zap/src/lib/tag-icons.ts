/** De-dupe glyphs globally (first category wins) and drop invalid placeholders. */
function buildCategories(raw: readonly TagIconCategory[]): TagIconCategory[] {
  const seen = new Set<string>();
  return raw
    .map((cat) => ({
      id: cat.id,
      label: cat.label,
      icons: cat.icons.filter((icon) => {
        // Skip accidental non-emoji placeholders
        if (icon.glyph.length > 16 || /^[a-z]/i.test(icon.glyph)) return false;
        if (seen.has(icon.glyph)) return false;
        seen.add(icon.glyph);
        return true;
      }),
    }))
    .filter((cat) => cat.icons.length > 0);
}

export const TAG_ICON_CATEGORIES: readonly TagIconCategory[] = buildCategories(RAW_CATEGORIES);

const ALL = new Set(TAG_ICON_CATEGORIES.flatMap((c) => c.icons.map((x) => x.glyph)));

const SEARCHABLE = TAG_ICON_CATEGORIES.flatMap((cat) =>
  cat.icons.map((icon) => ({
    glyph: icon.glyph,
    haystack: `${cat.label} ${cat.id} ${icon.keys} ${icon.glyph}`.toLowerCase(),
  }))
);

/** True when `value` is one of the curated system icons. */
export function isSystemTagIcon(value: string | null | undefined): boolean {
  if (!value) return false;
  return ALL.has(value.trim());
}

/** Normalize admin input: trim, accept only curated icons, else null. */
export function normalizeTagIcon(raw: unknown): string | null {
  if (raw == null) return null;
  const value = String(raw).trim();
  if (!value) return null;
  return ALL.has(value) ? value : null;
}

export function tagIconOrEmpty(icon: string | null | undefined): string {
  return icon && ALL.has(icon) ? icon : "";
}

export function systemTagIconCount(): number {
  return ALL.size;
}

/** Filter categories by free-text query (keywords, category label, or glyph). */
export function filterTagIconCategories(query: string): TagIconCategory[] {
  const trimmed = query.trim();
  const needle = trimmed.toLowerCase();
  if (!needle) return [...TAG_ICON_CATEGORIES];

  const matched = new Set(
    SEARCHABLE.filter((row) => row.haystack.includes(needle) || row.glyph === trimmed).map((row) => row.glyph)
  );

  return TAG_ICON_CATEGORIES.map((cat) => ({
    ...cat,
    icons: cat.icons.filter((icon) => matched.has(icon.glyph)),
  })).filter((cat) => cat.icons.length > 0);
}
